def _is_int(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def load_plan(path: str | os.PathLike[str]) -> list[dict[str, Any]]:
    plan_path = Path(path)
    try:
        text = plan_path.read_text(encoding="utf-8-sig")
    except Exception as exc:
        raise PlanError("plan-unreadable") from exc
    rows: list[dict[str, Any]] = []
    for line_number, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        try:
            item = json.loads(line)
        except Exception as exc:
            raise PlanError("plan-json-invalid") from exc
        if not isinstance(item, dict):
            raise PlanError("plan-row-invalid")
        rows.append(item)
    if not rows:
        raise PlanError("plan-empty")
    return rows


def _plan_dag_ok(rows: Sequence[Mapping[str, Any]]) -> bool:
    ids = {str(row.get("id")) for row in rows}
    indegree = {item: 0 for item in ids}
    children: dict[str, list[str]] = collections.defaultdict(list)
    for row in rows:
        parent = str(row.get("id"))
        for dependency in row.get("depends_on", []) or []:
            dep = str(dependency)
            if dep not in ids:
                return False
            indegree[parent] += 1
            children[dep].append(parent)
    queue = collections.deque(sorted(item for item, degree in indegree.items() if degree == 0))
    visited = 0
    while queue:
        node = queue.popleft()
        visited += 1
        for child in sorted(children.get(node, [])):
            indegree[child] -= 1
            if indegree[child] == 0:
                queue.append(child)
    return visited == len(ids)


def validate_plan(rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Validate the shared batch contract and calculate phase totals."""
    issues: list[str] = []
    ids: list[str] = []
    phase_totals: dict[str, dict[str, int]] = {
        phase: {"batches": 0, "loc_target": 0, "production_loc": 0, "test_loc": 0}
        for phase in PHASES
    }
    id_pattern = re.compile(r"^ATLAS-P([0-8])-(\d{4})$")
    numeric_ids: list[int] = []
    for index, row in enumerate(rows, 1):
        row_id = row.get("id")
        if not isinstance(row_id, str):
            issues.append(f"row-{index}-id-invalid")
            continue
        ids.append(row_id)
        match = id_pattern.fullmatch(row_id)
        if not match:
            issues.append(f"{row_id}-id-format-invalid")
        else:
            numeric_ids.append(int(match.group(2)))
            phase = row.get("phase")
            if phase != "P" + match.group(1):
                issues.append(f"{row_id}-phase-id-mismatch")
        phase = row.get("phase")
        if phase not in PHASE_TARGETS:
            issues.append(f"{row_id}-phase-invalid")
        elif not isinstance(row.get("module"), str) or not row.get("module"):
            issues.append(f"{row_id}-module-invalid")
        for field in ("depends_on", "inputs", "outputs", "acceptance", "reviewer"):
            if field not in row:
                issues.append(f"{row_id}-{field}-missing")
        depends = row.get("depends_on", [])
        if not isinstance(depends, list) or any(not isinstance(dep, str) for dep in depends):
            issues.append(f"{row_id}-dependencies-invalid")
        for field in ("loc_target", "production_loc", "test_loc"):
            if field in row and not _is_int(row[field]):
                issues.append(f"{row_id}-{field}-invalid")
        loc = row.get("loc_target")
        if _is_int(loc) and not 800 <= loc <= 2_500:
            issues.append(f"{row_id}-loc-range-invalid")
        production = row.get("production_loc")
        test = row.get("test_loc")
        if _is_int(production) and _is_int(test) and _is_int(loc) and production + test != loc:
            issues.append(f"{row_id}-loc-split-invalid")
        if phase in phase_totals and _is_int(loc):
            phase_totals[phase]["batches"] += 1
            phase_totals[phase]["loc_target"] += loc
            if _is_int(production):
                phase_totals[phase]["production_loc"] += production
            if _is_int(test):
                phase_totals[phase]["test_loc"] += test
    if len(set(ids)) != len(ids):
        issues.append("duplicate-batch-id")
    if numeric_ids and sorted(numeric_ids) != list(range(1, len(numeric_ids) + 1)):
        issues.append("batch-sequence-not-contiguous")
    for row in rows:
        row_id = row.get("id")
        if not isinstance(row_id, str):
            continue
        for dependency in row.get("depends_on", []) or []:
            if isinstance(dependency, str):
                dep_match = id_pattern.fullmatch(dependency)
                current_match = id_pattern.fullmatch(row_id)
                if dep_match and current_match and int(dependency.rsplit("-", 1)[1]) >= int(row_id.rsplit("-", 1)[1]):
                    issues.append(f"{row_id}-dependency-not-earlier")
    if not _plan_dag_ok(rows):
        issues.append("dependency-cycle")
    if len(rows) < 340 or len(rows) > 400:
        issues.append("batch-count-out-of-contract-range")
    for phase, target in PHASE_TARGETS.items():
        if phase_totals[phase]["loc_target"] != target:
            issues.append(f"{phase}-loc-target-mismatch")
    total = sum(item["loc_target"] for item in phase_totals.values())
    if total != 560_000:
        issues.append("total-loc-target-mismatch")
    return {
        "batches": len(rows),
        "total_loc": total,
        "production_loc": sum(item["production_loc"] for item in phase_totals.values()),
        "test_loc": sum(item["test_loc"] for item in phase_totals.values()),
        "phases": [
            {
                "phase": phase,
                **phase_totals[phase],
                "target": PHASE_TARGETS[phase],
                "delta": phase_totals[phase]["loc_target"] - PHASE_TARGETS[phase],
            }
            for phase in PHASES
        ],
        "issues": sorted(set(issues)),
        "status": "pass" if not issues else "fail",
    }


